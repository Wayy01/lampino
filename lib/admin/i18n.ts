export type AdminDict = typeof ro;
export type AdminLang = Locale;

export const adminDictionaries: Record<AdminLang, AdminDict> = { ro, ru };

export function getAdminDict(lang: AdminLang): AdminDict {
  return adminDictionaries[lang] ?? adminDictionaries.ro;
}

/** Translated label for any status string, falling back to the raw value. */
export function statusLabel(t: AdminDict, status: string): string {
  return (t.statuses as Record<string, string>)[status] ?? status;
}

/** Translated label for a rental event type, falling back to the raw value. */
export function eventLabel(t: AdminDict, eventType: string): string {
  return (t.events as Record<string, string>)[eventType] ?? eventType;
}

/** Prefix an admin-relative path with `/admin/<lang>`; server-safe. */
export function adminHref(lang: AdminLang, path = ""): string {
  return `/admin/${lang}${path}`;
}

/** Read the locale a form was submitted from (hidden `_lang` field). */
export function langFromForm(fd: FormData): AdminLang {
  const raw = String(fd.get("_lang") ?? "");
  return raw === "ru" ? "ru" : "ro";
}
